import Foundation

/// 分类名 → emoji 图标（纯函数，无状态）
enum CategoryIcon {
    static func guess(_ name: String) -> String {
        let table: [(String, String)] = [
            ("餐", "🍜"), ("饭", "🍜"), ("food", "🍜"), ("咖", "☕"),
            ("交通", "🚇"), ("车", "🚗"), ("地铁", "🚇"),
            ("购", "🛍️"), ("衣", "👕"), ("数码", "📱"),
            ("日用", "🧴"), ("超市", "🛒"),
            ("房", "🏠"), ("租", "🏠"), ("水", "💧"), ("电", "💡"), ("燃气", "🔥"),
            ("通讯", "📱"), ("话费", "📞"), ("网", "🌐"),
            ("娱乐", "🎮"), ("游戏", "🎮"), ("电影", "🎬"),
            ("医", "💊"), ("药", "💊"),
            ("学", "📚"), ("书", "📖"),
            ("人情", "🎁"), ("礼", "🎁"),
            ("旅", "✈️"),
            ("工资", "💰"), ("薪", "💰"), ("奖", "🏆"), ("兼职", "🛠️"),
            ("理财", "📈"), ("投资", "📈"), ("报销", "🧾")
        ]
        for (k, v) in table where name.contains(k) { return v }
        return "🏷️"
    }
}
